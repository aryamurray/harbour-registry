#!/usr/bin/env python3
"""Render packages/ into index/ (and the README package table), or check that it is.

    render.py                  render every package
    render.py zlib libpng      render just these
    render.py --check          exit 1, with a readable diff, if the checkout is not
                               exactly what the sources produce
    render.py --check --base origin/main
                               also enforce append-only publication: a shim or patch
                               that exists at the base ref must be byte-identical now
    render.py --harbour BIN    let `BIN registry index` write (or, with --check,
                               verify) the .idx files instead of trusting the built-in
                               port; this downloads every package's source

What is rendered, per package (see README.md, "Layout"):

  * the NEWEST [[release]] in package.toml: its shim `<version>.toml`, the patch
    `<version>.patch` that adds Harbour.toml + overlay/, and one patch per file in
    patches/. These are rewritten from the package's current files.
  * OLDER [[release]]s are never rewritten (the index is append-only for a
    version once published: users' lockfiles pin the patch hash). They are only
    checked: shim present, pin matches package.toml, patch hashes consistent.
  * `<name>.idx`, listing every version; an older version's record is carried over.

Exit status: 0 ok / rendered, 1 the checkout is stale or inconsistent, 2 usage.
"""
from __future__ import annotations

import argparse
import difflib
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import regtools as rt
from regtools import RegistryError

README = rt.ROOT / "README.md"
TABLE_BEGIN = "<!-- packages:begin (generated by tools/render.py; do not edit) -->"
TABLE_END = "<!-- packages:end -->"


# ---------------------------------------------------------------------------
# Expected tree
# ---------------------------------------------------------------------------

def expected_for(pkg: rt.Package, index: Path, problems: list[str]) -> dict[str, bytes]:
    """{path relative to index/: bytes} that `pkg` must own in the index."""
    out: dict[str, bytes] = {}
    newest = pkg.newest
    rendered = rt.render_release(pkg, newest)
    out.update(rendered.files)

    shims: dict[str, dict] = {newest.version: rt.parse_shim(rendered.files[rendered.shim_rel].decode())}
    listed = {r.version for r in pkg.releases}

    # Versions on disk that package.toml does not list.
    d = rt.shim_dir(pkg.name, index=index)
    on_disk = sorted(p.stem for p in d.glob("*.toml")) if d.is_dir() else []
    for v in on_disk:
        if v not in listed:
            problems.append(f"index/{pkg.name[0]}/{pkg.name}/{v}.toml exists but package.toml has no "
                            f"[[release]] version = \"{v}\" (the history must stay listed)")

    for old in pkg.releases[1:]:
        shim_file = d / f"{old.version}.toml"
        if not shim_file.is_file():
            problems.append(
                f"{pkg.name} {old.version}: listed in package.toml but index/ has no shim for it. Only the "
                "newest release is rendered (older releases' Harbour.toml and overlay are not kept): "
                "add a new release by bumping Harbour.toml, or delete this [[release]] entry")
            continue
        text = shim_file.read_bytes()
        shim = rt.parse_shim(text.decode())
        problems.extend(check_old_release(pkg, old, shim, d))
        out[f"{pkg.name[0]}/{pkg.name}/{old.version}.toml"] = text
        for patch in shim.get("patches", []):
            f = d / patch["file"]
            if f.is_file():
                out[f"{pkg.name[0]}/{pkg.name}/{patch['file']}"] = f.read_bytes()
        shims[old.version] = shim

    manifest = rt.read_toml(pkg.dir / "Harbour.toml")
    deps = rt.manifest_deps(manifest, f"{pkg.name}/Harbour.toml")
    previous = rt.read_idx(rt.idx_path(pkg.name, index=index))
    try:
        idx = rt.render_idx(pkg, shims, previous, deps)
    except RegistryError as err:
        problems.append(str(err))
        idx = ""
    out[f"{pkg.name[0]}/{pkg.name}.idx"] = idx.encode("utf-8")
    return out


def check_old_release(pkg: rt.Package, rel_: rt.Release, shim: dict, d: Path) -> list[str]:
    """An older release is frozen: verify it, never rewrite it."""
    who = f"{pkg.name} {rel_.version}"
    problems = []
    if shim.get("package", {}).get("name") != pkg.name or shim.get("package", {}).get("version") != rel_.version:
        problems.append(f"{who}: the shim names {shim.get('package')} (expected this package and version)")
    src = shim.get("source", {})
    if rel_.sha256 is not None:
        if src.get("tarball", {}).get("sha256") != rel_.sha256:
            problems.append(f"{who}: package.toml pins sha256 {rel_.sha256} but the published shim pins "
                            f"{src.get('tarball', {}).get('sha256')}")
    elif rel_.rev is not None:
        if src.get("git", {}).get("rev") != rel_.rev:
            problems.append(f"{who}: package.toml pins rev {rel_.rev} but the published shim pins "
                            f"{src.get('git', {}).get('rev')}")
    for patch in shim.get("patches", []):
        f = d / patch["file"]
        if not f.is_file():
            problems.append(f"{who}: patch {patch['file']} listed in the shim is missing")
        elif hashlib.sha256(f.read_bytes()).hexdigest() != patch["sha256"]:
            problems.append(f"{who}: patch {patch['file']} does not match the sha256 its shim lists")
    return problems


def readme_table(pkgs: list[rt.Package]) -> str:
    rows = ["| package | version | license | platforms | description |", "| --- | --- | --- | --- | --- |"]
    for p in pkgs:
        rows.append(f"| [{p.name}](packages/{p.name}) | {p.newest.version} | `{p.license}` | "
                    f"{', '.join(p.platforms())} | {p.data['package']['description']} |")
    return "\n".join(rows)


def rendered_readme(text: str, pkgs: list[rt.Package]) -> str:
    a, b = text.find(TABLE_BEGIN), text.find(TABLE_END)
    if a < 0 or b < a:
        raise RegistryError(f"README.md must contain the markers {TABLE_BEGIN!r} and {TABLE_END!r}")
    return text[: a + len(TABLE_BEGIN)] + "\n" + readme_table(pkgs) + "\n" + text[b:]


# ---------------------------------------------------------------------------
# harbour registry index (authoritative .idx)
# ---------------------------------------------------------------------------

def harbour_idx(binary: str, files: dict[str, bytes]) -> dict[str, bytes]:
    """Run `harbour registry index` over `files` (a rendered index/) and return its .idx files."""
    with tempfile.TemporaryDirectory(prefix="registry-index-") as tmp:
        tmp_root = Path(tmp)
        for relpath, data in files.items():
            dest = tmp_root / "index" / relpath
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(data)
        shutil.copy(rt.ROOT / "config.toml", tmp_root / "config.toml")
        shutil.copy(rt.ROOT / ".gitattributes", tmp_root / ".gitattributes")
        proc = subprocess.run([binary, "registry", "index", str(tmp_root)], capture_output=True, text=True)
        if proc.returncode:
            raise RegistryError(f"`{binary} registry index` failed:\n{proc.stdout}{proc.stderr}")
        return {
            p.relative_to(tmp_root / "index").as_posix(): p.read_bytes()
            for p in (tmp_root / "index").rglob("*.idx")
        }


# ---------------------------------------------------------------------------
# Comparison / output
# ---------------------------------------------------------------------------

def disk_tree(index: Path) -> dict[str, bytes]:
    if not index.is_dir():
        return {}
    return {p.relative_to(index).as_posix(): p.read_bytes() for p in sorted(index.rglob("*")) if p.is_file()}


def show_diff(path: str, want: bytes | None, have: bytes | None, limit: int = 40) -> str:
    if want is None:
        return f"  unexpected file: index/{path} (no package produces it)"
    if have is None:
        return f"  missing file:    index/{path}"
    try:
        a = have.decode("utf-8").splitlines(keepends=True)
        b = want.decode("utf-8").splitlines(keepends=True)
    except UnicodeDecodeError:
        return f"  differs (binary): index/{path}"
    lines = list(difflib.unified_diff(a, b, f"index/{path} (checked in)", f"index/{path} (rendered)", n=1))
    more = len(lines) - limit
    body = "".join(lines[:limit])
    if more > 0:
        body += f"... {more} more diff lines\n"
    if not lines:
        body = "  (line endings or trailing bytes differ)\n"
    return body.rstrip("\n")


def git_show(ref: str, path: str) -> bytes | None:
    proc = subprocess.run(["git", "-C", str(rt.ROOT), "show", f"{ref}:{path}"], capture_output=True)
    return proc.stdout if proc.returncode == 0 else None


def check_append_only(ref: str, pkgs: list[rt.Package], want: dict[str, bytes]) -> list[str]:
    """A published version's shim and patches must be byte-identical to what `ref` had.

    This is what keeps a lockfile's pinned patch hash valid. `.idx` files may change
    (they gain a line per release). A release can opt out with
    `republish = "<reason>"` in package.toml, which is then visible in review.
    """
    probe = subprocess.run(["git", "-C", str(rt.ROOT), "rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}"],
                           capture_output=True)
    if probe.returncode:
        raise RegistryError(f"--base {ref}: not a commit in this checkout (is the history fetched?)")
    listing = subprocess.run(["git", "-C", str(rt.ROOT), "ls-tree", "-r", "--name-only", ref, "index/"],
                             capture_output=True, text=True, check=True).stdout.split("\n")
    exempt = {(p.name, r.version) for p in pkgs for r in p.releases if r.republish}
    problems = []
    for path in filter(None, listing):
        if path.endswith(".idx"):
            continue
        parts = path.split("/")  # index / l / name / <version>[-fix].{toml,patch}
        if len(parts) != 4:
            continue
        name, fname = parts[2], parts[3]
        version = next((v for (n, v) in exempt if n == name and fname.startswith(v)), None)
        if version is not None:
            continue
        now = want.get(path[len("index/"):])
        if now is None:
            problems.append(f"{path}: published at {ref} but would be deleted. Published versions are never removed")
        else:
            old = git_show(ref, path)
            if old != now:
                problems.append(
                    f"{path}: published at {ref} but would change. A patch's sha256 is pinned by users' lockfiles, "
                    "so a published version is immutable: release a new version instead, or (humans only) "
                    "set `republish = \"<reason>\"` on that [[release]] to acknowledge breaking the pin")
    return problems


