def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("packages", nargs="*", help="render only these packages (default: all)")
    ap.add_argument("--check", action="store_true", help="verify instead of writing; exit 1 if stale")
    ap.add_argument("--base", metavar="REF", help="with --check: enforce append-only against this git ref")
    ap.add_argument("--harbour", metavar="BIN", help="use `BIN registry index` for the .idx files")
    ap.add_argument("--normalize-version", metavar="UPSTREAM", help="print the semver for an upstream version and exit")
    args = ap.parse_args(argv)

    if args.normalize_version:
        try:
            print(rt.normalize_version(args.normalize_version))
        except RegistryError as err:
            print(f"render.py: {err}", file=sys.stderr)
            return 1
        return 0

    try:
        all_pkgs = rt.load_all()
        names = {p.name for p in all_pkgs}
        unknown = [n for n in args.packages if n not in names]
        if unknown:
            print(f"render.py: no such package: {', '.join(unknown)} (have: {', '.join(sorted(names))})", file=sys.stderr)
            return 2
        selected = [p for p in all_pkgs if not args.packages or p.name in args.packages]
        return run(args, all_pkgs, selected)
    except RegistryError as err:
        print(f"render.py: {err}", file=sys.stderr)
        return 1


def run(args, all_pkgs: list[rt.Package], selected: list[rt.Package]) -> int:
    problems: list[str] = []
    want: dict[str, bytes] = {}
    for pkg in all_pkgs:
        want.update(expected_for(pkg, rt.INDEX, problems))

    if args.harbour:
        authoritative = harbour_idx(args.harbour, {k: v for k, v in want.items()})
        for path, data in authoritative.items():
            if path in want and want[path] != data:
                if args.check:
                    problems.append(f"the built-in .idx renderer and `harbour registry index` disagree on "
                                    f"index/{path} (tools/regtools.py needs fixing):\n"
                                    + show_diff(path, data, want[path]))
                want[path] = data  # harbour is authoritative

    have = disk_tree(rt.INDEX)
    scope = {p.name for p in selected}

    def owner_of(path: str) -> str:
        parts = path.split("/")  # l/libpng.idx | l/libpng/1.6.50.toml
        return parts[1].removesuffix(".idx")

    # Files in index/ that no package produces.
    orphans = sorted(p for p in have if p not in want and owner_of(p) not in {x.name for x in all_pkgs})
    stale_known = sorted(p for p in have if p not in want and owner_of(p) in scope)
    for p in orphans:
        problems.append(f"index/{p} belongs to no package under packages/ (remove it with `git rm`, or restore its package)")

    readme_old = README.read_bytes().decode("utf-8") if README.is_file() else ""
    try:
        readme_new = rendered_readme(readme_old, all_pkgs)
    except RegistryError as err:
        problems.append(str(err))
        readme_new = readme_old

    changed = [p for p in sorted(want) if owner_of(p) in scope and have.get(p) != want[p]]

    if args.check:
        diffs = [show_diff(p, want[p], have.get(p)) for p in changed]
        diffs += [show_diff(p, None, have[p]) for p in stale_known]
        if readme_new != readme_old:
            diffs.append("  README.md: the package table is stale:\n" + show_diff("../README.md", readme_new.encode(), readme_old.encode()).replace("index/../", ""))
        if args.base:
            problems.extend(check_append_only(args.base, all_pkgs, want))
        if diffs or problems:
            print("index/ is NOT what packages/ renders to.\n")
            for d in diffs:
                print(d + "\n")
            for pr in problems:
                print(f"error: {pr}")
            print("\nFix: run `python3 tools/render.py` and commit the result"
                  + (" (and address the errors above)." if problems else "."))
            return 1
        print(f"ok: index/ matches packages/ for {len(all_pkgs)} package(s)"
              + (f"; append-only against {args.base}" if args.base else ""))
        return 0

    if problems:
        for pr in problems:
            print(f"error: {pr}", file=sys.stderr)
        return 1
    for p in changed:
        dest = rt.INDEX / p
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(want[p])
        print(f"wrote index/{p}")
    for p in stale_known:
        (rt.INDEX / p).unlink()
        print(f"removed index/{p}")
    if readme_new != readme_old:
        README.write_bytes(readme_new.encode("utf-8"))
        print("wrote README.md (package table)")
    if not changed and not stale_known:
        print("index/ already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
