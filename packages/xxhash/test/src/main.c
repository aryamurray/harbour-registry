/* Exercise xxhash against PUBLISHED known answers.
 *
 * The expected values below are rows of upstream's own test vectors, tests/sanity_test_vectors.h
 * at v0.8.4, for the input that upstream's sanity test generates (see fill() below, the same
 * recurrence as fillTestBuffer() in tests/sanity_test.c). They were not computed with this build.
 * Lengths are chosen to cross every code path of XXH3 (0, 1-3, 4-8, 9-16, 17-128, 129-240, >240)
 * and XXH32/XXH64 (the <16 and <32 tails, the stripe loop). Each row is checked one-shot, and the
 * XXH32/XXH64/XXH3-64 rows also through the streaming API fed in uneven pieces. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include <xxhash.h>

/* tools/test.py exports the upstream version that package.toml declares. */
static int version_is_declared(unsigned number) {
    char got[32];
    snprintf(got, sizeof(got), "%u.%u.%u", number / 10000u, (number / 100u) % 100u, number % 100u);
    const char *want = getenv("REGISTRY_TEST_UPSTREAM_VERSION");
    if (want == NULL || *want == '\0') {
        printf("FAIL: REGISTRY_TEST_UPSTREAM_VERSION is not set (run this through tools/test.py)\n");
        return 0;
    }
    if (strcmp(want, got) != 0) {
        printf("FAIL: XXH_versionNumber() reports version %s, but package.toml declares %s\n", got, want);
        return 0;
    }
    return 1;
}

static int failures = 0;

#define CHECK(cond)                                                            \
    do {                                                                       \
        if (!(cond)) {                                                         \
            printf("FAIL line %d: %s\n", __LINE__, #cond);                     \
            failures++;                                                        \
        }                                                                      \
    } while (0)

#define PRIME32 2654435761U
#define PRIME64 11400714785074694797ULL

/* tests/sanity_test.c fillTestBuffer(): its values must never change upstream. */
static void fill(unsigned char *buf, size_t n) {
    unsigned long long gen = PRIME32;
    for (size_t i = 0; i < n; i++) {
        buf[i] = (unsigned char) (gen >> 56);
        gen *= PRIME64;
    }
}

