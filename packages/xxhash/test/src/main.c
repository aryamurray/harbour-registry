#define COUNT(a) (sizeof(a) / sizeof((a)[0]))

int main(void) {
    if (!version_is_declared(XXH_versionNumber())) return 1;
    CHECK(XXH_versionNumber() == XXH_VERSION_NUMBER);

    unsigned char *buf = malloc(2048);
    if (buf == NULL) {
        printf("FAIL: out of memory\n");
        return 1;
    }
    fill(buf, 2048);

    for (size_t i = 0; i < COUNT(xxh32_vectors); i++) {
        const v32_t *v = &xxh32_vectors[i];
        CHECK(XXH32(buf, v->len, v->seed) == v->expect);
        XXH32_state_t *st = XXH32_createState();
        CHECK(st != NULL);
        if (st != NULL) {
            CHECK(XXH32_reset(st, v->seed) == XXH_OK);
            size_t half = v->len / 3;
            CHECK(XXH32_update(st, buf, half) == XXH_OK);
            CHECK(XXH32_update(st, buf + half, v->len - half) == XXH_OK);
            CHECK(XXH32_digest(st) == v->expect);
            XXH32_freeState(st);
        }
    }

    for (size_t i = 0; i < COUNT(xxh64_vectors); i++) {
        const v64_t *v = &xxh64_vectors[i];
        CHECK(XXH64(buf, v->len, v->seed) == v->expect);
        XXH64_state_t *st = XXH64_createState();
        CHECK(st != NULL);
        if (st != NULL) {
            CHECK(XXH64_reset(st, v->seed) == XXH_OK);
            size_t half = v->len / 3;
            CHECK(XXH64_update(st, buf, half) == XXH_OK);
            CHECK(XXH64_update(st, buf + half, v->len - half) == XXH_OK);
            CHECK(XXH64_digest(st) == v->expect);
            XXH64_freeState(st);
        }
    }

    for (size_t i = 0; i < COUNT(xxh3_vectors); i++) {
        const v64_t *v = &xxh3_vectors[i];
        CHECK(XXH3_64bits_withSeed(buf, v->len, v->seed) == v->expect);
        if (v->seed == 0) CHECK(XXH3_64bits(buf, v->len) == v->expect);
        XXH3_state_t *st = XXH3_createState();
        CHECK(st != NULL);
        if (st != NULL) {
            CHECK(XXH3_64bits_reset_withSeed(st, v->seed) == XXH_OK);
            size_t half = v->len / 3;
            CHECK(XXH3_64bits_update(st, buf, half) == XXH_OK);
            CHECK(XXH3_64bits_update(st, buf + half, v->len - half) == XXH_OK);
            CHECK(XXH3_64bits_digest(st) == v->expect);
            XXH3_freeState(st);
        }
    }

    for (size_t i = 0; i < COUNT(xxh128_vectors); i++) {
        const v128_t *v = &xxh128_vectors[i];
        XXH128_hash_t h = XXH3_128bits_withSeed(buf, v->len, v->seed);
        CHECK(h.low64 == v->low && h.high64 == v->high);
        XXH128_hash_t e;
        e.low64 = v->low;
        e.high64 = v->high;
        CHECK(XXH128_isEqual(h, e) == 1);
    }

    free(buf);

    if (failures != 0) {
        printf("%d check(s) failed\n", failures);
        return 1;
    }
    printf("OK xxhash %u.%u.%u: %u published XXH32/XXH64/XXH3/XXH128 vectors, one-shot and streaming\n",
           XXH_VERSION_MAJOR, XXH_VERSION_MINOR, XXH_VERSION_RELEASE,
           (unsigned) (COUNT(xxh32_vectors) + COUNT(xxh64_vectors) + COUNT(xxh3_vectors) + COUNT(xxh128_vectors)));
    return 0;
}
